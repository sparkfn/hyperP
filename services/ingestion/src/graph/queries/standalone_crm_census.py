ADMIT_CENSUS = (
    "MERGE (scope:StandaloneCrmCensusActiveScope {scope_key: $scope_key}) "
    "WITH scope OPTIONAL MATCH (scope)-[:HAS_ACTIVE_CENSUS]->(active:StandaloneCrmCensus) "
    "WITH scope, collect(active) AS active_rows "
    "OPTIONAL MATCH (replay:StandaloneCrmCensus {source_key: $source_key, "
    "source_instance_id: $source_instance_id, control_instance_id: $control_instance_id, "
    "census_kind: $census_kind, occurrence_key: $occurrence_key}) "
    "WITH scope, active_rows, replay WHERE size(active_rows) <= 1 "
    "AND (replay IS NOT NULL OR size(active_rows) = 0) "
    "MERGE (census:StandaloneCrmCensus {source_key: $source_key, source_instance_id: $source_instance_id, "
    "control_instance_id: $control_instance_id, census_kind: $census_kind, occurrence_key: $occurrence_key}) "
    "ON CREATE SET census.census_id = $census_id, census.fingerprint = $fingerprint, census.request_json = $request_json, "
    "census.authority_revision = $authority_revision, census.authority_json = $authority_json, census.status = 'allocated', "
    "census.generation = 0, census.attempt_count = 0, census.occurrence_calls = 0, census.occurrence_rows = 0, "
    "census.created_at = datetime(), census.updated_at = datetime() "
    "WITH scope, census, replay WHERE census.fingerprint = $fingerprint "
    "FOREACH (_ IN CASE WHEN NOT (census.status IN ['completed', 'failed', 'cancelled_with_checkpoint', 'freeze_failed']) "
    "THEN [1] ELSE [] END | MERGE (scope)-[:HAS_ACTIVE_CENSUS]->(census)) "
    "WITH census, replay "
    "WITH census, replay IS NOT NULL AS replayed "
    "RETURN census.census_id AS census_id, census.status AS status, replayed, "
    "census.fingerprint = $fingerprint AS fingerprint_match"
)

