RESERVE_CALL = (
    "MATCH (census:StandaloneCrmCensus {census_id: $census_id, generation: $generation}) "
    "MATCH (attempt:StandaloneCrmCensusAttempt {census_id: $census_id, generation: $generation, status: 'running'}) "
    "WHERE coalesce(census.cancel_requested, false) = false AND census.census_kind = 'source_sync' "
    "AND census.authority_revision = $authority_revision AND census.authority_json = $authority_json "
    "AND EXISTS { MATCH (instance:BitrixSourceInstance {status: 'active'})-[:INSTANCE_OF]->"
    "(source:SourceSystem {is_active: true}) WHERE instance.source_key = census.source_key "
    "AND instance.source_instance_id = census.source_instance_id AND source.source_key = census.source_key } "
    "AND EXISTS { MATCH (binding:BitrixExecutionSourceBinding) WHERE binding.source_key = census.source_key "
    "AND binding.source_instance_id = census.source_instance_id AND binding.control_instance_id = census.control_instance_id } "
    "AND census.status IN ['freezing', 'running', 'publishing', 'recovering'] "
    "AND datetime() < datetime($deadline) AND datetime() < attempt.attempt_deadline "
    "AND attempt.lease_until >= datetime() "
    "AND census.occurrence_calls < $occurrence_call_limit "
    "AND coalesce(attempt.call_count, 0) < $attempt_call_limit "
    "AND (($call_kind = 'probe' AND attempt.fence_token = $fence_token AND attempt.task_id = $task_id) OR EXISTS { MATCH (unit:StandaloneCrmCensusUnit {census_id: $census_id, "
    "generation: $generation, stream_kind: $stream_kind}) MATCH (unit_fence:StandaloneCrmCensusFence {"
    "census_id: $census_id, generation: $generation, stream_kind: $stream_kind, token: $fence_token, "
    "status: 'active'}) MATCH (publication:StandaloneCrmChildPublication {census_id: $census_id, "
    "generation: $generation, stream_kind: $stream_kind, task_id: $task_id, status: 'published'}) "
    "WHERE unit.state IN ['running', 'paused'] AND unit_fence.lease_until >= datetime() }) "
    "SET census.call_sequence = coalesce(census.call_sequence, 0) + 1 "
    "WITH census, attempt "
    "CREATE (call:StandaloneCrmHttpCallReservation {intent_id: $intent_id, census_id: $census_id, "
    "generation: $generation, fence_token: $fence_token, call_kind: $call_kind, stream_kind: $stream_kind, "
    "call_sequence: census.call_sequence, retry_ordinal: $retry_ordinal, cursor: $cursor, subject_id: $subject_id, "
    "reserved_deadline: datetime($deadline), effective_deadline: datetime($effective_deadline), "
    "task_id: $task_id, status: 'reserved', created_at: datetime()}) "
    "SET census.occurrence_calls = census.occurrence_calls + 1, attempt.call_count = coalesce(attempt.call_count, 0) + 1 "
    "RETURN call.intent_id AS intent_id, call.call_sequence AS call_sequence"
)

