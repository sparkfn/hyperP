    "stream_kind: $stream_kind, generation: $generation, fence_token: $fence_token, "
    "frozen_upper_id: $frozen_upper_id}) "
    "WHERE coalesce(census.cancel_requested, false) = false "
    "AND census.status IN ['running', 'publishing', 'recovering'] "
    "AND fence.lease_until >= datetime() AND datetime() < datetime($occurrence_deadline) "
    "AND datetime() < attempt.attempt_deadline "
    "AND EXISTS { MATCH (instance:BitrixSourceInstance {status: 'active'})-[:INSTANCE_OF]->"
    "(source:SourceSystem {is_active: true}) WHERE instance.source_key = census.source_key "
    "AND instance.source_instance_id = census.source_instance_id AND source.source_key = census.source_key } "
