    "stream_kind: $stream_kind, state: 'running', frozen_upper_id: $frozen_upper_id}) "
    "MATCH (fence:StandaloneCrmCensusFence {census_id: $census_id, generation: $generation, "
    "stream_kind: $stream_kind, token: $fence_token, owner_id: $owner_id, status: 'active'}) "
