SETTLE_CANCELLATION = (
    "MATCH (census:StandaloneCrmCensus {census_id: $census_id, generation: $generation, "
    "cancel_requested: true}) "
    "WHERE census.authority_revision = $authority_revision AND census.authority_json = $authority_json "
    "AND EXISTS { MATCH (instance:BitrixSourceInstance {status: 'active'})-[:INSTANCE_OF]->(source:SourceSystem {is_active: true}) WHERE instance.source_key = census.source_key AND instance.source_instance_id = census.source_instance_id AND source.source_key = census.source_key } "
    "AND EXISTS { MATCH (binding:BitrixExecutionSourceBinding) WHERE binding.source_key = census.source_key AND binding.control_instance_id = census.control_instance_id AND binding.source_instance_id = census.source_instance_id } "
    "OPTIONAL MATCH (publication:StandaloneCrmChildPublication {census_id: $census_id, generation: $generation}) "
    "WITH census, collect(publication) AS publications "
    "OPTIONAL MATCH (unit:StandaloneCrmCensusUnit {census_id: $census_id, generation: $generation}) "
    "WITH census, publications, collect(unit) AS units "
    "WHERE all(unit IN units WHERE unit IS NULL OR NOT (unit.state IN ['running', 'paused']) "
    "OR EXISTS { MATCH (checkpoint:StandaloneCrmCensusCheckpoint {census_id: $census_id, "
    "stream_kind: unit.stream_kind, generation: $generation}) "
    "MATCH (:StandaloneCrmCensusFence {census_id: $census_id, stream_kind: unit.stream_kind, "
    "generation: $generation, token: checkpoint.fence_token, status: 'active'}) }) "
    "FOREACH (publication IN [publication IN publications WHERE publication.status IN ['pending', 'publishing', 'published']] | "
    "SET publication.status = 'retired', publication.retired_at = datetime(), publication.updated_at = datetime()) "
    "FOREACH (unit IN [unit IN units WHERE unit.state IN ['pending_publication', 'publishing', 'queued']] | "
    "SET unit.state = 'cancelled', unit.stop_requested = true, unit.updated_at = datetime()) "
    "FOREACH (unit IN [unit IN units WHERE unit.state IN ['running', 'paused']] | "
    "SET unit.state = 'cancelled', unit.stop_requested = true, unit.cancelled_at = datetime(), unit.updated_at = datetime()) "
    "WITH census, units "
    "OPTIONAL MATCH (fence:StandaloneCrmCensusFence {census_id: $census_id, generation: $generation, status: 'active'}) "
    "FOREACH (_ IN CASE WHEN fence IS NULL THEN [] ELSE [1] END | "
    "SET fence.status = 'retired', fence.retired_at = datetime(), fence.updated_at = datetime()) "
    "WITH census OPTIONAL MATCH (attempt:StandaloneCrmCensusAttempt {census_id: $census_id, generation: $generation, status: 'running'}) "
    "FOREACH (_ IN CASE WHEN attempt IS NULL THEN [] ELSE [1] END | "
    "SET attempt.status = 'completed', attempt.updated_at = datetime()) "
    "RETURN census.census_id AS census_id"
)

