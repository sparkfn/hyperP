STORE_CHECKPOINT = (
    "MATCH (census:StandaloneCrmCensus {census_id: $census_id, generation: $generation}) "
    "OPTIONAL MATCH (attempt:StandaloneCrmCensusAttempt {census_id: $census_id, generation: $generation, fence_token: $fence_token, status: 'running'}) "
    "OPTIONAL MATCH (unit:StandaloneCrmCensusUnit {census_id: $census_id, generation: $generation, stream_kind: $stream_kind}) "
    "OPTIONAL MATCH (fence:StandaloneCrmCensusFence {census_id: $census_id, generation: $generation, stream_kind: $stream_kind, token: $fence_token, status: 'active'}) "
    "OPTIONAL MATCH (checkpoint:StandaloneCrmCensusCheckpoint {census_id: $census_id, stream_kind: $stream_kind}) "
    "WITH census, attempt, unit, fence, checkpoint, $processed_rows - coalesce(checkpoint.processed_rows, 0) AS row_delta "
    "WITH census, attempt, unit, fence, checkpoint, row_delta, "
    "CASE WHEN attempt IS NOT NULL AND unit IS NOT NULL AND fence IS NOT NULL "
    "AND census.status IN ['running', 'publishing', 'recovering', 'cancel_requested'] "
    "AND (coalesce(census.cancel_requested, false) = false OR $allow_cancel_checkpoint = true) "
    "AND census.authority_revision = $authority_revision AND census.authority_json = $authority_json "
    "AND fence.lease_until >= datetime() AND datetime() < datetime($occurrence_deadline) "
    "AND datetime() < attempt.attempt_deadline "
    "AND EXISTS { MATCH (instance:BitrixSourceInstance {status: 'active'})-[:INSTANCE_OF]->(source:SourceSystem {is_active: true}) "
    "WHERE instance.source_key = census.source_key AND instance.source_instance_id = census.source_instance_id AND source.source_key = census.source_key } "
    "AND EXISTS { MATCH (binding:BitrixExecutionSourceBinding) WHERE binding.source_key = census.source_key "
    "AND binding.control_instance_id = census.control_instance_id AND binding.source_instance_id = census.source_instance_id } "
    "AND coalesce(checkpoint.last_committed_id, -1) <= $last_committed_id "
    "AND coalesce(checkpoint.processed_rows, 0) <= $processed_rows "
    "AND coalesce(checkpoint.skipped_rows, 0) <= $skipped_rows "
    "AND (checkpoint IS NULL OR (checkpoint.binding_subject_id IS NULL AND $binding_subject_id IS NULL) "
    "OR (checkpoint.binding_subject_id IS NOT NULL AND $binding_subject_id IS NOT NULL "
    "AND ($binding_subject_id > checkpoint.binding_subject_id OR ($binding_subject_id = checkpoint.binding_subject_id "
    "AND $binding_offset >= checkpoint.binding_offset)))) "
    "AND (checkpoint IS NULL OR checkpoint.frozen_upper_id = unit.frozen_upper_id) "
    "AND (checkpoint IS NULL OR coalesce(checkpoint.revision_id, '') = coalesce(unit.revision_id, '')) "
    "THEN true ELSE false END AS valid "
    "WITH census, attempt, unit, checkpoint, row_delta, valid, "
    "CASE WHEN NOT valid OR row_delta < 0 THEN 'stale_or_conflict' "
    "WHEN coalesce(census.occurrence_rows, 0) + row_delta > $occurrence_row_limit THEN 'occurrence_exhausted' "
    "WHEN coalesce(attempt.row_count, 0) + row_delta > $attempt_row_limit THEN 'attempt_exhausted' "
    "ELSE 'stored' END AS decision "
    "FOREACH (_ IN CASE WHEN decision = 'stored' THEN [1] ELSE [] END | "
    "MERGE (stored:StandaloneCrmCensusCheckpoint {census_id: $census_id, stream_kind: $stream_kind}) "
    "SET stored.last_committed_id = $last_committed_id, stored.processed_rows = $processed_rows, stored.skipped_rows = $skipped_rows, "
    "stored.binding_subject_id = $binding_subject_id, stored.binding_offset = $binding_offset, stored.fence_token = $fence_token, "
    "stored.generation = $generation, stored.frozen_upper_id = unit.frozen_upper_id, stored.revision_id = unit.revision_id, stored.updated_at = datetime(), "
    "census.occurrence_rows = coalesce(census.occurrence_rows, 0) + row_delta, attempt.row_count = coalesce(attempt.row_count, 0) + row_delta) "
    "FOREACH (_ IN CASE WHEN decision = 'attempt_exhausted' THEN [1] ELSE [] END | "
    "SET attempt.status = 'paused_with_checkpoint', census.status = 'paused_with_checkpoint', census.pause_reason = 'attempt_budget_exhausted', census.updated_at = datetime()) "
    "FOREACH (_ IN CASE WHEN decision = 'occurrence_exhausted' THEN [1] ELSE [] END | "
    "SET attempt.status = 'failed', attempt.failure_reason = 'occurrence_budget_exhausted', census.status = 'failed', "
    "census.terminal_reason = 'occurrence_budget_exhausted', census.terminal_at = datetime(), census.updated_at = datetime()) "
    "RETURN decision AS decision"
)

