SETTLE_UNIT = (
    "MATCH (census:StandaloneCrmCensus {census_id: $census_id, generation: $generation}) "
    "MATCH (unit:StandaloneCrmCensusUnit {census_id: $census_id, stream_kind: $stream_kind, generation: $generation}) "
    "OPTIONAL MATCH (fence:StandaloneCrmCensusFence {census_id: $census_id, stream_kind: $stream_kind, "
    "generation: $generation, token: $fence_token, status: 'active'}) "
    "WITH census, unit, fence "
    "WHERE ($no_work OR fence IS NOT NULL) AND census.authority_revision = $authority_revision "
    "AND census.authority_json = $authority_json "
    "AND (coalesce(census.cancel_requested, false) = false OR $allow_cancel_settlement = true) "
    "AND EXISTS { MATCH (instance:BitrixSourceInstance {status: 'active'})-[:INSTANCE_OF]->(source:SourceSystem {is_active: true}) "
    "WHERE instance.source_key = census.source_key AND instance.source_instance_id = census.source_instance_id AND source.source_key = census.source_key } "
    "AND EXISTS { MATCH (binding:BitrixExecutionSourceBinding) WHERE binding.source_key = census.source_key "
    "AND binding.control_instance_id = census.control_instance_id AND binding.source_instance_id = census.source_instance_id } "
    "SET unit.state = $unit_state, unit.stop_requested = coalesce(census.cancel_requested, false), "
    "unit.updated_at = datetime() "
    "FOREACH (_ IN CASE WHEN fence IS NULL THEN [] ELSE [1] END | "
    "SET fence.status = 'retired', fence.retired_at = datetime(), fence.updated_at = datetime()) "
    "WITH unit OPTIONAL MATCH (publication:StandaloneCrmChildPublication {census_id: $census_id, "
    "generation: $generation, stream_kind: $stream_kind}) "
    "WITH unit, collect(publication) AS publications "
    "FOREACH (publication IN [item IN publications WHERE $unit_state IN ['completed', 'failed', 'cancelled'] "
    "AND item.status <> 'retired'] | "
    "SET publication.status = 'retired', publication.retired_at = datetime(), publication.updated_at = datetime()) "
    "RETURN unit.stream_kind AS stream_kind"
)

